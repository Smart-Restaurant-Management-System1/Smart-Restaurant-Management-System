        ws.Column(4).Width = Math.Max(ws.Column(4).Width, 24);
        ws.Column(5).Width = Math.Max(ws.Column(5).Width, 30);
        ws.Column(6).Width = Math.Max(ws.Column(6).Width, 20);
        ws.Column(8).Width = Math.Max(ws.Column(8).Width, 16);
        ws.Column(13).Width = Math.Max(ws.Column(13).Width, 22);

        using var ms = new MemoryStream();
        workbook.SaveAs(ms);
        return ms.ToArray();
    }

