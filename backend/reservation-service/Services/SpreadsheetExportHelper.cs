        sub.Style.Font.Bold = true;
        sub.Style.Font.FontSize = 9;
        sub.Style.Font.FontColor = XLColor.White;
        sub.Style.Fill.BackgroundColor = XLColor.FromHtml("#C5A059");
        sub.Style.Alignment.Horizontal = XLAlignmentHorizontalValues.Center;
        sub.Style.Alignment.Vertical = XLAlignmentVerticalValues.Center;
        ws.Row(3).Height = 18;

        // 3. Metadata summary
