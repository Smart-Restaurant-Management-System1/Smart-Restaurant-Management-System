    public static byte[] BuildReservationsCsvWithMetadata(
        IReadOnlyList<Reservation> reservations,
        AdminReservationQuery query,
        string? adminEmail = null)
    {
        var builder = new StringBuilder();

        // 1. Data Table Headers (Strict RFC 4180 - uniform 13 columns across all records)
        var headers = new[]
        {
            "Reservation ID", "Booking Reference", "Customer ID", "Customer Name", "Customer Email",
            "Customer Phone", "Table Number", "Visit Date", "Start Time", "End Time",
            "Guest Count", "Status", "Created At (UTC)"
        };
        builder.AppendLine(string.Join(",", headers.Select(EscapeCsvField)));

        // 3. Rows
        foreach (var res in reservations)
        {
            var row = new[]
            {
                res.Id.ToString(CultureInfo.InvariantCulture),
                res.BookingReference,
                res.CustomerId.ToString(CultureInfo.InvariantCulture),
                string.IsNullOrWhiteSpace(res.CustomerName) ? "Guest" : res.CustomerName,
                res.CustomerEmail,
                // Prefix phone with tab in CSV so Excel interprets it as Text without scientific notation
                "\t" + (res.CustomerPhone ?? string.Empty),
                string.IsNullOrWhiteSpace(res.TableNumber) ? "N/A" : res.TableNumber,
                res.StartDateTime.ToString("yyyy-MM-dd"),
                res.StartDateTime.ToString("HH:mm"),
                res.EndDateTime.ToString("HH:mm"),
                res.GuestCount.ToString(CultureInfo.InvariantCulture),
                res.Status,
                res.CreatedAt.ToString("yyyy-MM-dd HH:mm:ss")
            };
            builder.AppendLine(string.Join(",", row.Select(EscapeCsvField)));
        }

        return EncodeUtf8Bom(builder.ToString());
    }

    public static byte[] BuildOrdersCsvWithMetadata(
        IReadOnlyList<AdminOrderItemDto> orders,
        AdminOrderQueryDto query,
        string? adminEmail = null)
    {
        var builder = new StringBuilder();

        // 1. Data Table Headers (Strict RFC 4180 - uniform 14 columns across all records)
        var headers = new[]
        {
            "Order ID", "Order Reference", "Order Type", "Table Number", "Reservation ID",
            "Customer ID", "Customer Name", "Customer Email", "Customer Phone", "Order Status",
            "Total Amount (LKR)", "Payment Status", "Payment Method", "Created At (UTC)"
        };
        builder.AppendLine(string.Join(",", headers.Select(EscapeCsvField)));

        // 3. Rows
        foreach (var ord in orders)
        {
            var row = new[]
            {
                ord.OrderId.ToString(CultureInfo.InvariantCulture),
                ord.OrderReference,
                ord.OrderType == "ReservationPreOrder" ? "Reservation Pre-order" : "Dine-in",
                string.IsNullOrWhiteSpace(ord.TableNumber) ? "N/A" : ord.TableNumber,
                ord.ReservationId.HasValue ? ord.ReservationId.Value.ToString(CultureInfo.InvariantCulture) : "N/A",
                ord.CustomerId.ToString(CultureInfo.InvariantCulture),
                string.IsNullOrWhiteSpace(ord.CustomerName) ? "Guest" : ord.CustomerName,
                ord.CustomerEmail,
                "\t" + (ord.CustomerPhone ?? string.Empty),
                ord.Status,
                ord.TotalAmount.ToString("F2", CultureInfo.InvariantCulture),
                ord.PaymentStatus,
                string.IsNullOrWhiteSpace(ord.PaymentMethod) ? "N/A" : ord.PaymentMethod,
                ord.CreatedAt.ToString("yyyy-MM-dd HH:mm:ss")
            };
            builder.AppendLine(string.Join(",", row.Select(EscapeCsvField)));
        }

        return EncodeUtf8Bom(builder.ToString());
    }

    private static byte[] EncodeUtf8Bom(string content)
    {
        var encoding = new UTF8Encoding(true);
        var preamble = encoding.GetPreamble();
        var body = encoding.GetBytes(content);

        var result = new byte[preamble.Length + body.Length];
        Buffer.BlockCopy(preamble, 0, result, 0, preamble.Length);
        Buffer.BlockCopy(body, 0, result, preamble.Length, body.Length);
        return result;
    }
