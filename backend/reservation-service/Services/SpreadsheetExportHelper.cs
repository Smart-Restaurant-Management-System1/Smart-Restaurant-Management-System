        {
            "Reservation ID", "Booking Reference", "Customer ID", "Customer Name", "Customer Email",
            "Customer Phone", "Table Number", "Visit Date", "Start Time", "End Time",
            "Guest Count", "Status", "Created At (UTC)"
        };

        ws.Row(9).Height = 26;
        for (int i = 0; i < headers.Length; i++)
        {
            var cell = ws.Cell(9, i + 1);
            cell.Value = headers[i];
            cell.Style.Font.Bold = true;
            cell.Style.Font.FontSize = 9.5;
            cell.Style.Font.FontColor = XLColor.White;
            cell.Style.Fill.BackgroundColor = XLColor.FromHtml("#1E293B");
            cell.Style.Alignment.Vertical = XLAlignmentVerticalValues.Center;
