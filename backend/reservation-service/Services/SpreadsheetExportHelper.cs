            {
                var c = ws.Cell(rowNum, col);
                c.Style.Font.FontSize = 9;
                c.Style.Font.FontColor = XLColor.FromHtml("#201A15");
                c.Style.Fill.BackgroundColor = rowBg;
                c.Style.Border.OutsideBorder = XLBorderStyleValues.Thin;
                c.Style.Border.OutsideBorderColor = XLColor.FromHtml("#E2E8F0");
                c.Style.Alignment.Vertical = XLAlignmentVerticalValues.Center;

                if (col == 1 || col == 2 || col == 3 || col == 7 || col == 8 || col == 9 || col == 10 || col == 11 || col == 13)
                {
                    c.Style.Alignment.Horizontal = XLAlignmentHorizontalValues.Center;
                }
            }

            var st = (res.Status ?? "").ToLowerInvariant();
            statusCell.Style.Font.Bold = true;
            statusCell.Style.Alignment.Horizontal = XLAlignmentHorizontalValues.Center;
            if (st == "confirmed")
            {
                statusCell.Style.Font.FontColor = XLColor.FromHtml("#047857");
                statusCell.Style.Fill.BackgroundColor = XLColor.FromHtml("#ECFDF5");
            }
            else if (st == "pending")
            {
                statusCell.Style.Font.FontColor = XLColor.FromHtml("#B45309");
                statusCell.Style.Fill.BackgroundColor = XLColor.FromHtml("#FFFBEB");
            }
            else if (st == "cancelled")
            {
                statusCell.Style.Font.FontColor = XLColor.FromHtml("#991B1B");
                statusCell.Style.Fill.BackgroundColor = XLColor.FromHtml("#FEF2F2");
            }
            else if (st == "completed")
            {
                statusCell.Style.Font.FontColor = XLColor.FromHtml("#1D4ED8");
                statusCell.Style.Fill.BackgroundColor = XLColor.FromHtml("#EFF6FF");
            }
        }

