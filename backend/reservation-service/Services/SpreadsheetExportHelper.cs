        {
            cell.Value = text;
            cell.Style.Font.Bold = true;
            cell.Style.Font.FontSize = 9;
            cell.Style.Font.FontColor = XLColor.FromHtml("#475569");
            cell.Style.Fill.BackgroundColor = XLColor.FromHtml("#F8FAFC");
            cell.Style.Alignment.Vertical = XLAlignmentVerticalValues.Center;
        }
        void StyleMetaValue(IXLCell cell, string text)
        {
            cell.Value = text;
            cell.Style.Font.FontSize = 9;
            cell.Style.Font.FontColor = XLColor.FromHtml("#1E293B");
            cell.Style.Alignment.Vertical = XLAlignmentVerticalValues.Center;
        }

        ws.Row(5).Height = 20;
        StyleMetaLabel(ws.Cell("B5"), "Date Window:");
        var fromStr = query.VisitFrom?.ToString("yyyy-MM-dd") ?? "Start";
        var toStr = query.VisitTo?.ToString("yyyy-MM-dd") ?? "Present";
        StyleMetaValue(ws.Cell("C5"), $"{fromStr} to {toStr}");

        StyleMetaLabel(ws.Cell("E5"), "Generated Date (UTC):");
        StyleMetaValue(ws.Cell("F5"), DateTime.UtcNow.ToString("yyyy-MM-dd HH:mm:ss") + " UTC");

        ws.Row(6).Height = 20;
        StyleMetaLabel(ws.Cell("B6"), "Status Filter:");
        StyleMetaValue(ws.Cell("C6"), string.IsNullOrWhiteSpace(query.Status) ? "All Statuses" : query.Status);

        StyleMetaLabel(ws.Cell("E6"), "Generated By:");
        StyleMetaValue(ws.Cell("F6"), string.IsNullOrWhiteSpace(adminEmail) ? "System Administrator" : adminEmail);

